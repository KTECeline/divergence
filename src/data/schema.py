"""Schema for one skill run: a MalSkillBench skill plus the trace it produced.

MalSkillBench ships skills, not traces; every trace was generated by running
the skill once in the sealed sandbox (Stage 2). So a sample is a *run*, and it
carries two different labels that must not be confused:

  * dataset_label — what MalSkillBench says the skill IS (1 = malicious).
  * observed_outcome — what the agent actually DID in this run (e.g. it may
    have recognised the payload and declined, leaving a harmless trace).

The training target for Divergence is decided from the observed behaviour
after the hand review (Stage 3), not from dataset_label alone.
"""

from dataclasses import asdict, dataclass, field


@dataclass
class SkillSample:
    """One run: declared description, normalised action trace, and labels."""

    sample_id: str  # "<malware|benign>/<skill folder name>"
    skill_name: str
    description: str  # SKILL.md frontmatter description (what a user is shown)
    trace: list[dict]  # normalised actions (src/preprocessing/normalise_trace.py)
    dataset_label: int  # 1 = malicious in MalSkillBench, 0 = benign

    # MalSkillBench taxonomy (GENERATED malicious only; WILD/benign leave these None)
    source: str | None = None  # GENERATED / WILD / None for benign
    attack_vector: str | None = None  # CI / PI / MIXED
    behaviour_class: str | None = None  # B1..B15
    insertion_strategy: str | None = None

    group_key: str = ""  # split grouping: variants of one skill share a key
    has_scripts: bool = False
    execution_mode: str = "agent"  # "agent" (Stage 2) or "direct" (Stage 3, no agent)
    observed_outcome: str = ""  # provisional, from src/data/outcome.py
    signals: dict = field(default_factory=dict)  # behaviour signals behind it
    timed_out: bool = False
    metadata: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict) -> "SkillSample":
        return cls(**d)
